"""AGENT.md generator.

Produces an editable specification that keeps four registers apart:
observed facts, inferences, proposed design, and open questions.
"""

from __future__ import annotations

from typing import List

from . import __version__
from .evidence import Finding, Investigation

MODES = {
    "understand": "Understand Only",
    "build": "Independent Build Plan",
    "modernize": "Modernize / Migrate",
    "documentation": "Complete Project Documentation",
}


def _by(inv: Investigation, category: str) -> List[Finding]:
    return [f for f in inv.findings if f.category == category]


def _bullets(findings: List[Finding], limit: int = 8) -> List[str]:
    return [f"* {f.claim} _({f.id}, {f.status.value}, {f.confidence.value})_" for f in findings[:limit]]


def _observed(inv: Investigation) -> List[str]:
    strong = [f for f in inv.findings if f.status.value == "OBSERVED"]
    return _bullets(strong, 12)


def _inferred(inv: Investigation) -> List[str]:
    weak = [f for f in inv.findings if f.status.value == "INFERRED"]
    return _bullets(weak, 8)


def _unknowns(inv: Investigation) -> List[str]:
    open_items = [f for f in inv.findings if f.status.value in {"UNKNOWN", "NOT_CHECKED", "CONTRADICTED"}]
    return _bullets(open_items, 8)


def generate_agent_md(inv: Investigation, mode: str = "understand") -> str:
    if mode not in MODES:
        raise ValueError(f"unknown mode {mode!r}; choose from {', '.join(MODES)}")

    stack = _by(inv, "overview.stack")
    routes = _by(inv, "api.routes")
    deps = _by(inv, "dependencies.declared")
    tests = _by(inv, "quality.tests")

    lines: List[str] = []
    add = lines.append
    add("# AGENT.md")
    add("")
    add(f"> Generated by ProtectREVERSE {__version__} from investigation `{inv.id}`")
    add(f"> Mode: **{MODES[mode]}**")
    add("> This file mixes evidence with proposals. Registers are labelled; do not read a proposal as a fact.")
    add("")

    add("## 1. Overview")
    add("")
    purpose = _by(inv, "overview.purpose")
    if purpose:
        add(f"The project describes itself as: {purpose[0].claim} _({purpose[0].id}, OBSERVED)_")
    else:
        add("No self-description was found in the repository. Treat the purpose as unknown.")
    add("")
    add(f"* Target: `{inv.target}` ({inv.target_kind})")
    if inv.meta.get("revision"):
        add(f"* Pinned revision: `{inv.meta['revision'][:12]}`")
    add("")

    add("## 2. Observed facts")
    add("")
    add("\n".join(_observed(inv)) or "* No directly observed facts were recorded.")
    add("")

    add("## 3. Inferences (not proof)")
    add("")
    add("\n".join(_inferred(inv)) or "* None recorded.")
    add("")

    if stack:
        add("## 4. Technology baseline")
        add("")
        add("\n".join(_bullets(stack, 6)))
        add("")

    if deps:
        add("## 5. Declared dependencies")
        add("")
        add(f"{deps[0].claim}")
        add("")
        add("Proposed: keep the dependency set minimal and pin it in a lockfile before adding new packages.")
        add("")

    if routes:
        add("## 6. HTTP surface")
        add("")
        add(routes[0].claim)
        endpoints = routes[0].details.get("endpoints", [])[:12]
        for endpoint in endpoints:
            add(f"* `{endpoint['method']} {endpoint['path']}` — {endpoint['file']}:{endpoint['line']}")
        add("")

    add("## 7. Proposed architecture (PROPOSAL — not observed)")
    add("")
    if mode == "build":
        add("The following structure is proposed for an independent implementation. It is deliberately "
            "generic; adapt it to the observed stack rather than copying it.")
        add("")
        add("```")
        add("app/")
        add("  entrypoint/      # process start, configuration loading")
        add("  domain/          # pure logic, no I/O")
        add("  adapters/        # HTTP, database, external services")
        add("  observability/   # logs, metrics, redaction")
        add("tests/")
        add("  unit/ integration/ fixtures/")
        add("docs/")
        add("  architecture.md decisions/ runbook.md")
        add("```")
    elif mode == "modernize":
        add("Migration proposal: introduce a seam between domain logic and I/O before changing frameworks. "
            "Move one vertical slice at a time, keep the old path until parity tests pass.")
    elif mode == "documentation":
        add("Documentation proposal: one README for orientation, one architecture page per subsystem, "
            "one decision record per irreversible choice, and a runbook for operations.")
    else:
        add("No new architecture is proposed in Understand Only mode. This section restates the observed "
            "boundaries so a reader can see where they end.")
    add("")

    add("## 8. Requirements to confirm")
    add("")
    add("These are questions, not requirements. Each must be answered by the project owner before design work.")
    add("")
    for item in _unknowns(inv)[:6]:
        add(f"* [ ] {item}")
    add("")

    add("## 9. Testing strategy (proposal)")
    add("")
    if tests and "No tests were detected" not in tests[0].claim:
        add(f"Existing evidence: {tests[0].claim}")
    else:
        add("No tests were detected. Proposal: start with one end-to-end test of the primary path, "
            "then unit tests for the pure functions it touches.")
    add("")

    add("## 10. Milestones (proposal)")
    add("")
    add("1. Reproduce the current behaviour locally and record it as a baseline.")
    add("2. Add the smallest test that would catch a regression in that behaviour.")
    add("3. Close the highest-priority unknown from section 8.")
    add("4. Only then refactor or extend.")
    add("")

    add("## 11. Risks and limits")
    add("")
    add("* This specification was generated from static analysis; runtime behaviour is unverified.")
    add("* No source code was copied. Descriptions paraphrase observed structure.")
    add("* Third-party licences of any imported dependency must be checked separately.")
    add("")

    add("## 12. Coding-agent instructions")
    add("")
    add("* Treat this file as a starting brief, not as ground truth.")
    add("* Do not execute imported project code while exploring.")
    add("* Keep every claim traceable to a finding ID or mark it as an assumption.")
    add("* Stop and ask when a requirement in section 8 is still unanswered.")
    return "\n".join(lines)
